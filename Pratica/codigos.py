num = int(input('Digite um Numero: '))


if num < -0:
    print(f'O numero {num} é negativo.')

elif num > 0:
    print(f'O numero {num} é positivo.')

else: 
    print('Voce zerou')    

if num % 2 == 0:
    print(f'O numero {num} é par')
else:
    print(f'O numero {num} é impar.')    


    
    

